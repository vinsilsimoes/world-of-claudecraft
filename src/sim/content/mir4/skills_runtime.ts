export const MIR4_SKILLS: readonly Mir4SkillDef[] = [
  ...WARRIOR_SKILLS,
  ...SORCERER_SKILLS,
  ...TAOIST_SKILLS,
  ...ARBALIST_SKILLS,
  ...LANCER_SKILLS,
  ...EXTRACTED_MIR4_SKILLS.filter(
    (skill) =>
      skill.classId !== 1 &&
      skill.classId !== 2 &&
      skill.classId !== 3 &&
      skill.classId !== 4 &&
      skill.classId !== 5,
  ),
];

const SKILL_INDEX = new Map(MIR4_SKILLS.map((skill) => [skill.skillId, skill]));
const CLASS_SKILL_INDEX = new Map<number, Mir4SkillDef[]>();
for (const skill of MIR4_SKILLS) {
  const skills = CLASS_SKILL_INDEX.get(skill.classId) ?? [];
  skills.push(skill);
  CLASS_SKILL_INDEX.set(skill.classId, skills);
}
for (const skills of CLASS_SKILL_INDEX.values()) skills.sort((a, b) => a.slot - b.slot);

export function mir4SkillById(skillId: number): Mir4SkillDef | null {
  return SKILL_INDEX.get(skillId) ?? null;
}

export function mir4SkillsForClass(classId: 1 | 2 | 3 | 4 | 5): readonly Mir4SkillDef[] {
  return CLASS_SKILL_INDEX.get(classId) ?? [];
}
