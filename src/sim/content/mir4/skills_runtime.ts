// immutable; this layer composes that evidence with complete class kits from
// the official MIR4 client tables without rewriting the imported snapshot.

import { MIR4_NATIVE_SORCERER_SKILL_ACTIONS } from './native_skill_actions_sorcerer';
import {
  MIR4_SKILLS as EXTRACTED_MIR4_SKILLS,
  type Mir4SkillDef as ExtractedMir4SkillDef,
  type Mir4SkillEffect as ExtractedMir4SkillEffect,
} from './skills';

export interface Mir4SkillEffect extends ExtractedMir4SkillEffect {
  /** Entity that receives this effect. Hostile effects default to target. */
  subject?: 'actor' | 'target' | 'party';
  /** Radius used by party heals and party-wide support effects. */
  partyRadiusPx?: number;
  /** Deterministic cap for allies admitted by a party pulse. */
  maxPartyTargets?: number;
  /** Base native Spell ATK coefficient for one healing pulse, in basis points. */
  healSpellAttackBasisPoints?: number;
  /** Per-rank increase to the native healing coefficient, in basis points. */
  healSpellAttackLevelUpBasisPoints?: number;
  /** Flat healing added after the Spell ATK contribution to each pulse. */
  healFlat?: number;
  /** Number of one-second native healing pulses. */
  healPulseCount?: number;
  /** Milliseconds between native healing pulses. */
  healPulseIntervalMs?: number;
  /** Move the actor to the target before resolving the skill. */
  chargeToTarget?: boolean;
  /** Pull every enemy hit toward the actor after contact. */
  pullToActor?: boolean;
  /** Push every enemy hit away from the actor after contact. */
  pushFromActorYards?: number;
  /** Center used by circular secondary-target selection. Legacy rows default to target. */
  areaOrigin?: 'actor' | 'target' | 'forward';
  /** Spatial footprint used to admit secondary targets. Legacy rows default to circle. */
  areaShape?: 'circle' | 'frontal-strip';
  /** Distance from the actor to a forward-centered circle. */
  areaForwardOffsetPx?: number;
  /** Forward reach of a strip-shaped attack. */
  areaLengthPx?: number;
  /** Full lateral width of a strip-shaped attack. */
  areaWidthPx?: number;
  /** Step-up magnitude used from rank 10 onward by an already-supported effect kind. */
  rank10Magnitude?: number;
}

export interface Mir4SkillDef extends Omit<ExtractedMir4SkillDef, 'effect'> {
  effect: Mir4SkillEffect | null;
  /** Extra effects let one official skill damage enemies and buff its caster. */
  additionalEffects?: readonly Mir4SkillEffect[];
  /** Skill-specific admission range, used by gap closers. */
  castRangePx?: number;
  /** Damage-contact offsets recovered from the official SKILL_ATTACK rows. */
  impactOffsetsMs?: readonly number[];
}

function extractedSkill(skillId: number): Mir4SkillDef {
  const skill = EXTRACTED_MIR4_SKILLS.find((candidate) => candidate.skillId === skillId);
  if (!skill) throw new Error(`Missing extracted MIR4 skill ${skillId}`);
  return skill;
}

function extractedEffect(skillId: number): Mir4SkillEffect {
  const effect = extractedSkill(skillId).effect;
  if (!effect) throw new Error(`Missing extracted MIR4 skill effect ${skillId}`);
  return effect;
}

function damage(
  components: readonly [number, number, number, number?][],
  damageType = 1,
  damageAttribute = 0,
  allocationMode: NonNullable<Mir4SkillDef['damage']>['allocationMode'] = 'per-impact',
): Mir4SkillDef['damage'] {
  return {
    components: components.map(([attackId, coefficient, levelUpCoefficient, impactCount]) => ({
      attackId,
      damageType,
      damageAttribute,
      coefficient,
      levelUpCoefficient,
      impactCount: impactCount ?? 1,
    })),
    aggregateCoefficient: components.reduce((total, component) => total + component[1], 0),
    aggregateLevelUpCoefficient: components.reduce((total, component) => total + component[2], 0),
    allocationMode,
  };
}

const SORCERER_ACTION_BY_SKILL_ID = new Map(
  MIR4_NATIVE_SORCERER_SKILL_ACTIONS.map((action) => [action.skillId, action]),
);

interface NativeSorcererSkillOptions {
  readonly slot: number;
  readonly displayName: string;
  readonly unlock: Mir4SkillDef['unlock'];
  readonly roles: Mir4SkillDef['roles'];
  readonly allocationMode?: NonNullable<Mir4SkillDef['damage']>['allocationMode'];
  readonly impactOffsetsMs?: readonly number[];
  /**
   * Some cooked Sorcerer actions carry Targeting=true while their admitted
   * attack geometry is an actor-centred area. Keep that compatibility
   * interpretation explicit per reviewed skill instead of treating the raw
   * UI flag as a mandatory entity target.
   */
  readonly requiresTarget?: boolean;
  /** Compatibility-only behavior retained until that skill's own review. */
  readonly minTargets?: Mir4SkillDef['minTargets'];
  readonly effect?: Mir4SkillDef['effect'];
  readonly additionalEffects?: Mir4SkillDef['additionalEffects'];
}

/**
 * Project the shared Sorcerer runtime header and direct contacts from the
 * recovered SKILL/SKILL_ATTACK action instead of maintaining a second copy.
 * Buffs, projectiles, totems and rank passives remain fail-closed elsewhere
 * until their consumers are individually homologated.
 */
function nativeSorcererSkill(skillId: number, options: NativeSorcererSkillOptions): Mir4SkillDef {
  const action = SORCERER_ACTION_BY_SKILL_ID.get(skillId);
  if (!action) throw new Error(`Missing native Sorcerer action ${skillId}`);
  const damageRows = action.rows.filter((row) => row.damage.type !== 0);
  const firstRow = action.rows[0];
  if (!firstRow) throw new Error(`Missing native Sorcerer action row ${skillId}`);
  const directDamage =
    damageRows.length === 0
      ? null
      : {
          components: damageRows.map((row) => ({
            attackId: row.attackId,
            damageType: row.damage.type,
            damageAttribute: row.damage.attribute,
            coefficient: row.damage.coefficient,
            levelUpCoefficient: row.damage.levelUpCoefficient,
            impactCount: row.impactOffsetsMs.length,
          })),
          aggregateCoefficient: damageRows.reduce(
            (total, row) => total + row.damage.coefficient,
            0,
          ),
          aggregateLevelUpCoefficient: damageRows.reduce(
            (total, row) => total + row.damage.levelUpCoefficient,
            0,
          ),
          allocationMode: options.allocationMode ?? ('per-impact' as const),
        };
  return {
    skillId,
    classId: 2,
    slot: options.slot,
    displayName: options.displayName,
    unlock: options.unlock,
    cooldownMs: action.cooldownMs,
    skillCostType: action.skillCostType,
    skillCost: action.skillCost,
    attackAnimationMs: action.attackAnimationMs,
    hitCount: action.hitCount,
    impactOffsetsMs: options.impactOffsetsMs ?? damageRows.flatMap((row) => row.impactOffsetsMs),
    requiresTarget: options.requiresTarget ?? action.targeting,
    browserRangePx:
      (options.requiresTarget ?? action.targeting)
        ? (firstRow.targetDistance.nativeMax * 16) / 100
        : 0,
    attackIds: action.rows.map((row) => row.attackId),
    damage: directDamage,
    roles: options.roles,
    minTargets: options.minTargets ?? null,
    effect: options.effect ?? null,
    ...(options.additionalEffects ? { additionalEffects: options.additionalEffects } : {}),
    provenance: 'native-catalog',
    sourceRuntimeStatus: 'official-client-catalog',
  };
}

