function row(value: Omit<Mir4NativeSkillAttackRow, 'targetSubtype'>): Mir4NativeSkillAttackRow {
  return { ...value, targetSubtype: 'alive-only' };
}

function reaction(
  kind: Mir4NativeHitReaction['kind'],
  stance: Mir4NativeHitReaction['stance'],
  value: number,
  nativeHeight: number,
  valueEx: number,
  durationMs: number,
  probabilityPercent: number,
  direction: number,
): Mir4NativeHitReaction {
  return {
    kind,
    stance,
    value,
    nativeHeight,
    valueEx,
    durationMs,
    probabilityPercent,
    direction,
  };
}

