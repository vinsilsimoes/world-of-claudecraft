function indicator(nativeHeight: number): Mir4NativeSkillIndicator {
  return {
    type: 0,
    index: 0,
    angleDegrees: 0,
    nativeMin: 0,
    nativeMax: 0,
    nativeWidth: 0,
    nativeOffset: 0,
    nativeHeight,
  };
}

function geometry(
  angleDegrees: number,
  nativeDistanceMax: number,
  nativeWidth: number,
  nativeHeight: number,
  x = 0,
  y = 0,
  z = 0,
): Mir4NativeSkillGeometry {
  return {
    angleDegrees,
    nativeDistanceMin: 0,
    nativeDistanceMax,
    nativeWidth,
    nativeHeight,
    nativeOffset: { x, y, z },
    rotationDegrees: 0,
  };
}

function row(value: Omit<Mir4NativeSkillAttackRow, 'targetSubtype'>): Mir4NativeSkillAttackRow {
  return { ...value, targetSubtype: 'alive-only' };
}

