type PoiOccupants = 'citizens' | 'soldiers' | 'bandits' | 'undead' | 'wildlife' | 'guardians';
type PoiArchitecture =
  | 'mountain-pass'
  | 'abandoned-rampart'
  | 'highland-city'
  | 'petrified-root-quarry'
