import type { BiomePaint, HeightStamp, ZonePropsDef } from '../../types';

type Point = { x: number; z: number };
type MissionSiteId =
  | 'ownerless-walls'
  | 'breathing-quarry'
  | 'night-rampart'
  | 'golden-ascent'
  | 'root-crypt'
  | 'root-beacon';
