const M04_PRESENTATION_PAINT: BiomePaint = (() => {
  const cell = 12;
  const originX = 5120;
  const originZ = -160;
  const cols = Math.ceil((5960 - originX) / cell);
  const rows = Math.ceil((600 - originZ) / cell);
  const ellipse = (x: number, z: number, cx: number, cz: number, rx: number, rz: number) =>
    ((x - cx) / rx) ** 2 + ((z - cz) / rz) ** 2 <= 1;
  const ids = Array.from({ length: cols * rows }, (_, index) => {
    const col = index % cols;
    const row = Math.floor(index / cols);
    const x = originX + (col + 0.5) * cell;
    const z = originZ + (row + 0.5) * cell;
    if (x < 5900 && ellipse(x, z, 5860, 385, 72, 122)) return 8;
    if (ellipse(x, z, 5415, -55, 105, 100) || ellipse(x, z, 5710, 35, 86, 88)) return 6;
    if (ellipse(x, z, 5390, 250, 128, 132) || ellipse(x, z, 5650, 345, 82, 86)) return 10;
    return 16;
  });
  return { cell, cols, rows, originX, originZ, ids, affectsTerrain: false };
})();

